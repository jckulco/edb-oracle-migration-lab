-- =============================================================================
-- 01_tables.sql  |  Esquema destino en EDB Postgres Advanced Server
--
-- Decisiones de conversión (ver docs/05-mapeo-tipos-datos.md):
--   VARCHAR2(n)         -> varchar(n)
--   NUMBER(p,s)         -> numeric(p,s); IDs -> bigint
--   DATE (con hora)     -> timestamp(0)
--   TIMESTAMP           -> timestamp(6)
--   TIMESTAMP WITH TZ   -> timestamptz
--   CLOB / BLOB         -> text / bytea
--   RAW(16)             -> bytea
--   XMLTYPE             -> xml
--   JSON en CLOB        -> jsonb
--   Objeto T_DIRECCION  -> columnas planas dir_*
--   Nested table        -> text[]
--   Columna virtual     -> GENERATED ALWAYS AS ... STORED
--   Identidad           -> GENERATED BY DEFAULT AS IDENTITY
--
-- Las claves foráneas se agregan DESPUÉS de la carga (03_constraints.sql).
-- Los índices se crean DESPUÉS de la carga (02_indexes.sql).
-- =============================================================================
SET search_path TO ventas, public;

-- ---------------------------------------------------------------------------
-- Geografía
-- ---------------------------------------------------------------------------
CREATE TABLE regiones (
  region_id  bigint       CONSTRAINT pk_regiones PRIMARY KEY,
  nombre     varchar(60)  NOT NULL,
  codigo     char(2)      NOT NULL,
  CONSTRAINT uq_regiones_codigo UNIQUE (codigo)
);

CREATE TABLE paises (
  pais_id    bigint       CONSTRAINT pk_paises PRIMARY KEY,
  codigo     char(2)      NOT NULL,
  nombre     varchar(80)  NOT NULL,
  region_id  bigint       NOT NULL,
  CONSTRAINT uq_paises_codigo UNIQUE (codigo)
);

-- ---------------------------------------------------------------------------
-- Clientes
-- ---------------------------------------------------------------------------
CREATE TABLE clientes (
  cliente_id       bigint        CONSTRAINT pk_clientes PRIMARY KEY,
  codigo           varchar(20)   NOT NULL,
  nombre           varchar(120)  NOT NULL,
  email            varchar(160),
  telefono         varchar(30),
  fecha_alta       timestamp(0)  DEFAULT DATE '2020-01-01' NOT NULL,
  fecha_nacimiento timestamp(0),
  segmento         char(1)       DEFAULT 'C' NOT NULL,
  limite_credito   numeric(12,2) DEFAULT 0 NOT NULL,
  saldo            numeric(12,2) DEFAULT 0 NOT NULL,
  activo           char(1)       DEFAULT 'S' NOT NULL,
  dir_calle        varchar(150),
  dir_ciudad       varchar(80),
  dir_estado       varchar(80),
  dir_pais         char(2),
  dir_cp           varchar(12),
  telefonos        text[],
  notas            text,
  datos_extra      jsonb,
  nombre_mayus     varchar(120) GENERATED ALWAYS AS (upper(nombre)) STORED,
  creado_en        timestamp(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
  actualizado_en   timestamp(6),
  CONSTRAINT uq_clientes_codigo UNIQUE (codigo),
  CONSTRAINT ck_clientes_segmento CHECK (segmento IN ('A', 'B', 'C')),
  CONSTRAINT ck_clientes_activo   CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_clientes_saldo    CHECK (saldo >= 0),
  CONSTRAINT ck_clientes_json     CHECK
    (datos_extra IS NULL OR jsonb_typeof(datos_extra) = 'object')
);

CREATE TABLE direcciones_entrega (
  direccion_id  bigint        CONSTRAINT pk_direcciones PRIMARY KEY,
  cliente_id    bigint        NOT NULL,
  etiqueta      varchar(30)   DEFAULT 'PRINCIPAL' NOT NULL,
  calle         varchar(150)  NOT NULL,
  ciudad        varchar(80)   NOT NULL,
  estado        varchar(80),
  pais          char(2)       NOT NULL,
  codigo_postal varchar(12),
  es_principal  char(1)       DEFAULT 'N' NOT NULL,
  CONSTRAINT uq_direcciones_cliente_etiqueta UNIQUE (cliente_id, etiqueta),
  CONSTRAINT ck_direcciones_principal CHECK (es_principal IN ('S', 'N'))
);

-- ---------------------------------------------------------------------------
-- Catálogo
-- ---------------------------------------------------------------------------
CREATE TABLE categorias (
  categoria_id       bigint       CONSTRAINT pk_categorias PRIMARY KEY,
  nombre             varchar(80)  NOT NULL,
  categoria_padre_id bigint,
  activo             char(1)      DEFAULT 'S' NOT NULL,
  CONSTRAINT ck_categorias_activo CHECK (activo IN ('S', 'N'))
);

CREATE TABLE productos (
  producto_id    bigint        GENERATED BY DEFAULT AS IDENTITY
                               CONSTRAINT pk_productos PRIMARY KEY,
  sku            varchar(30)   NOT NULL,
  nombre         varchar(150)  NOT NULL,
  descripcion    text,
  categoria_id   bigint        NOT NULL,
  precio         numeric(12,2) NOT NULL,
  costo          numeric(12,2) NOT NULL,
  calificacion   real,
  peso_kg        numeric(8,3),
  garantia_meses numeric(3)    DEFAULT 0 NOT NULL,
  activo         char(1)       DEFAULT 'S' NOT NULL,
  imagen         bytea,
  ficha_xml      xml,
  atributos      jsonb,
  fecha_creacion timestamptz   DEFAULT CURRENT_TIMESTAMP NOT NULL,
  margen         numeric(12,2) GENERATED ALWAYS AS (precio - costo) STORED,
  CONSTRAINT uq_productos_sku UNIQUE (sku),
  CONSTRAINT ck_productos_precio CHECK (precio > 0),
  CONSTRAINT ck_productos_costo  CHECK (costo >= 0),
  CONSTRAINT ck_productos_activo CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_productos_calificacion CHECK (calificacion BETWEEN 0 AND 5),
  CONSTRAINT ck_productos_json CHECK
    (atributos IS NULL OR jsonb_typeof(atributos) = 'object')
);

-- ---------------------------------------------------------------------------
-- Empleados
-- ---------------------------------------------------------------------------
CREATE TABLE empleados (
  empleado_id   bigint        CONSTRAINT pk_empleados PRIMARY KEY,
  nombre        varchar(100)  NOT NULL,
  email         varchar(160)  NOT NULL,
  manager_id    bigint,
  fecha_ingreso timestamp(0)  NOT NULL,
  salario       numeric(10,2) NOT NULL,
  comision      numeric(5,2)  DEFAULT 0 NOT NULL,
  activo        char(1)       DEFAULT 'S' NOT NULL,
  CONSTRAINT uq_empleados_email UNIQUE (email),
  CONSTRAINT ck_empleados_salario CHECK (salario > 0),
  CONSTRAINT ck_empleados_comision CHECK (comision BETWEEN 0 AND 100),
  CONSTRAINT ck_empleados_activo CHECK (activo IN ('S', 'N'))
);

-- ---------------------------------------------------------------------------
-- Pedidos
-- ---------------------------------------------------------------------------
CREATE TABLE pedidos (
  pedido_id              bigint        CONSTRAINT pk_pedidos PRIMARY KEY,
  cliente_id             bigint        NOT NULL,
  empleado_id            bigint,
  fecha_pedido           timestamp(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
  fecha_entrega_estimada timestamp(0),
  fecha_entrega_real     timestamptz,
  estado                 varchar(20)   DEFAULT 'NUEVO' NOT NULL,
  moneda                 char(3)       DEFAULT 'MXN' NOT NULL,
  subtotal               numeric(14,2) DEFAULT 0 NOT NULL,
  impuesto               numeric(14,2) DEFAULT 0 NOT NULL,
  descuento              numeric(14,2) DEFAULT 0 NOT NULL,
  total                  numeric(14,2) DEFAULT 0 NOT NULL,
  notas                  text,
  creado_por             varchar(30)   DEFAULT upper(current_user) NOT NULL,
  tiempo_entrega         interval day to second,
  version                bigint        DEFAULT 1 NOT NULL,
  CONSTRAINT ck_pedidos_estado CHECK (estado IN
    ('NUEVO', 'CONFIRMADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')),
  CONSTRAINT ck_pedidos_moneda CHECK (moneda IN ('MXN', 'USD', 'EUR')),
  CONSTRAINT ck_pedidos_totales CHECK
    (subtotal >= 0 AND impuesto >= 0 AND descuento >= 0 AND total >= 0),
  CONSTRAINT ck_pedidos_version CHECK (version > 0)
);

CREATE TABLE pedido_detalle (
  detalle_id      bigint        GENERATED BY DEFAULT AS IDENTITY
                                CONSTRAINT pk_pedido_detalle PRIMARY KEY,
  pedido_id       bigint        NOT NULL,
  producto_id     bigint        NOT NULL,
  cantidad        numeric(10,3) NOT NULL,
  precio_unitario numeric(12,4) NOT NULL,
  descuento_pct   numeric(5,2)  DEFAULT 0 NOT NULL,
  total_linea     numeric(14,2) NOT NULL,
  CONSTRAINT uq_detalle_pedido_producto UNIQUE (pedido_id, producto_id),
  CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_descuento CHECK (descuento_pct BETWEEN 0 AND 100),
  CONSTRAINT ck_detalle_total_positivo CHECK (total_linea >= 0)
);

CREATE TABLE pagos (
  pago_id         bigint        CONSTRAINT pk_pagos PRIMARY KEY,
  pedido_id       bigint        NOT NULL,
  fecha_pago      timestamptz   DEFAULT CURRENT_TIMESTAMP NOT NULL,
  metodo          varchar(20)   NOT NULL,
  monto           numeric(14,2) NOT NULL,
  referencia      bytea,
  confirmado      char(1)       DEFAULT 'N' NOT NULL,
  datos_respuesta jsonb,
  CONSTRAINT ck_pagos_metodo CHECK
    (metodo IN ('TARJETA', 'TRANSFERENCIA', 'EFECTIVO', 'PAYPAL')),
  CONSTRAINT ck_pagos_confirmado CHECK (confirmado IN ('S', 'N')),
  CONSTRAINT ck_pagos_monto CHECK (monto > 0),
  CONSTRAINT ck_pagos_json CHECK
    (datos_respuesta IS NULL OR jsonb_typeof(datos_respuesta) = 'object')
);

-- ---------------------------------------------------------------------------
-- Auditoría e historial
-- ---------------------------------------------------------------------------
CREATE TABLE auditoria_cambios (
  auditoria_id  bigint       GENERATED BY DEFAULT AS IDENTITY
                             CONSTRAINT pk_auditoria PRIMARY KEY,
  tabla         varchar(30)  NOT NULL,
  operacion     char(1)      NOT NULL,
  pk_valor      varchar(100),
  usuario       varchar(30)  NOT NULL,
  fecha         timestamptz  DEFAULT CURRENT_TIMESTAMP NOT NULL,
  datos_antes   text,
  datos_despues text,
  origen        varchar(20)  DEFAULT 'TRIGGER' NOT NULL,
  CONSTRAINT ck_auditoria_operacion CHECK (operacion IN ('I', 'U', 'D'))
);

CREATE TABLE precios_historial (
  historial_id    bigint        CONSTRAINT pk_precios_historial PRIMARY KEY,
  producto_id     bigint        NOT NULL,
  precio_anterior numeric(12,2) NOT NULL,
  precio_nuevo    numeric(12,2) NOT NULL,
  fecha           timestamp(6)  DEFAULT CURRENT_TIMESTAMP NOT NULL,
  usuario         varchar(30)   NOT NULL
);

-- ---------------------------------------------------------------------------
-- Secuencias equivalentes a las de Oracle. Se resincronizan después de la
-- carga (09_after_load.sql) porque el ETL inserta IDs explícitos.
-- ---------------------------------------------------------------------------
CREATE SEQUENCE seq_clientes    START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_direcciones START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_pedidos     START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_pagos       START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE seq_historial   START WITH 1 INCREMENT BY 1;

-- ---------------------------------------------------------------------------
-- Comentarios
-- ---------------------------------------------------------------------------
COMMENT ON TABLE clientes IS
  'Clientes; objeto Oracle convertido a columnas planas y nested table a text[]';
COMMENT ON COLUMN clientes.datos_extra IS 'JSONB (origen: CLOB con CHECK IS JSON)';
COMMENT ON TABLE pedidos IS
  'Cabecera de pedidos; timestamp, interval y totales calculados';
COMMENT ON COLUMN pedidos.tiempo_entrega IS 'INTERVAL DAY TO SECOND';
COMMENT ON TABLE pagos IS 'Pagos; RAW(16) -> bytea y JSON -> jsonb';
COMMENT ON TABLE auditoria_cambios IS
  'Bitácora escrita por paquetes y triggers (transacción autónoma)';
COMMENT ON TABLE precios_historial IS 'Historial de cambios de precio';

ANALYZE;
