-- =============================================================================
-- 02_tables.sql  |  Modelo de datos del esquema VENTAS
--
-- El modelo simula una empresa de ventas con clientes, direcciones, catálogo,
-- pedidos, pagos, empleados jerárquicos y auditoría. Incluye deliberadamente
-- construcciones Oracle que obligan a tomar decisiones de migración:
--   NUMBER/VARCHAR2/DATE, CLOB/BLOB, RAW, XMLTYPE, JSON en CLOB,
--   INTERVAL, columnas virtuales, identidad, objeto y colección anidada,
--   DEFAULT USER, CHECK con IS JSON y claves foráneas diferidas.
-- =============================================================================
SET DEFINE OFF
ALTER SESSION SET TIME_ZONE = 'UTC';

-- ---------------------------------------------------------------------------
-- Geografía
-- ---------------------------------------------------------------------------
CREATE TABLE regiones (
  region_id  NUMBER(3)     CONSTRAINT pk_regiones PRIMARY KEY,
  nombre     VARCHAR2(60)  NOT NULL,
  codigo     CHAR(2)       NOT NULL,
  CONSTRAINT uq_regiones_codigo UNIQUE (codigo)
);

CREATE TABLE paises (
  pais_id    NUMBER(4)     CONSTRAINT pk_paises PRIMARY KEY,
  codigo     CHAR(2)       NOT NULL,
  nombre     VARCHAR2(80)  NOT NULL,
  region_id  NUMBER(3)     NOT NULL,
  CONSTRAINT uq_paises_codigo UNIQUE (codigo),
  CONSTRAINT fk_paises_region FOREIGN KEY (region_id) REFERENCES regiones (region_id)
);

-- ---------------------------------------------------------------------------
-- Clientes: objeto, colección anidada, CLOB, JSON, columna virtual y trigger
-- ---------------------------------------------------------------------------
CREATE TABLE clientes (
  cliente_id       NUMBER(10)    CONSTRAINT pk_clientes PRIMARY KEY,
  codigo           VARCHAR2(20)  NOT NULL,
  nombre           VARCHAR2(120) NOT NULL,
  email            VARCHAR2(160),
  telefono         VARCHAR2(30),
  fecha_alta       DATE          DEFAULT DATE '2020-01-01' NOT NULL,
  fecha_nacimiento DATE,
  segmento         CHAR(1)       DEFAULT 'C' NOT NULL,
  limite_credito   NUMBER(12,2)  DEFAULT 0 NOT NULL,
  saldo            NUMBER(12,2)  DEFAULT 0 NOT NULL,
  activo           CHAR(1)       DEFAULT 'S' NOT NULL,
  direccion        t_direccion,
  telefonos        t_telefonos,
  notas            CLOB,
  datos_extra      CLOB,
  nombre_mayus     VARCHAR2(120) GENERATED ALWAYS AS (UPPER(nombre)) VIRTUAL,
  creado_en        TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  actualizado_en   TIMESTAMP(6),
  CONSTRAINT uq_clientes_codigo UNIQUE (codigo),
  CONSTRAINT ck_clientes_segmento CHECK (segmento IN ('A', 'B', 'C')),
  CONSTRAINT ck_clientes_activo   CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_clientes_saldo    CHECK (saldo >= 0),
  CONSTRAINT ck_clientes_json     CHECK (datos_extra IS JSON)
) NESTED TABLE telefonos STORE AS nt_telefonos;

CREATE TABLE direcciones_entrega (
  direccion_id  NUMBER(10)    CONSTRAINT pk_direcciones PRIMARY KEY,
  cliente_id    NUMBER(10)    NOT NULL,
  etiqueta      VARCHAR2(30)  DEFAULT 'PRINCIPAL' NOT NULL,
  calle         VARCHAR2(150) NOT NULL,
  ciudad        VARCHAR2(80)  NOT NULL,
  estado        VARCHAR2(80),
  pais          CHAR(2)       NOT NULL,
  codigo_postal VARCHAR2(12),
  es_principal  CHAR(1)       DEFAULT 'N' NOT NULL,
  CONSTRAINT uq_direcciones_cliente_etiqueta UNIQUE (cliente_id, etiqueta),
  CONSTRAINT ck_direcciones_principal CHECK (es_principal IN ('S', 'N')),
  CONSTRAINT fk_direcciones_cliente FOREIGN KEY (cliente_id)
    REFERENCES clientes (cliente_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------------
-- Catálogo
-- ---------------------------------------------------------------------------
CREATE TABLE categorias (
  categoria_id       NUMBER(5)    CONSTRAINT pk_categorias PRIMARY KEY,
  nombre             VARCHAR2(80) NOT NULL,
  categoria_padre_id NUMBER(5),
  activo             CHAR(1)      DEFAULT 'S' NOT NULL,
  CONSTRAINT ck_categorias_activo CHECK (activo IN ('S', 'N')),
  CONSTRAINT fk_categorias_padre FOREIGN KEY (categoria_padre_id)
    REFERENCES categorias (categoria_id)
);

CREATE TABLE productos (
  producto_id    NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY
                               (START WITH 1 INCREMENT BY 1)
                               CONSTRAINT pk_productos PRIMARY KEY,
  sku            VARCHAR2(30)  NOT NULL,
  nombre         VARCHAR2(150) NOT NULL,
  descripcion    CLOB,
  categoria_id   NUMBER(5)     NOT NULL,
  precio         NUMBER(12,2)  NOT NULL,
  costo          NUMBER(12,2)  NOT NULL,
  calificacion   BINARY_FLOAT,
  peso_kg        NUMBER(8,3),
  garantia_meses NUMBER(3)     DEFAULT 0 NOT NULL,
  activo         CHAR(1)       DEFAULT 'S' NOT NULL,
  imagen         BLOB,
  ficha_xml      XMLTYPE,
  atributos      CLOB,
  fecha_creacion TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  margen         NUMBER(12,2)  GENERATED ALWAYS AS (precio - costo) VIRTUAL,
  CONSTRAINT uq_productos_sku UNIQUE (sku),
  CONSTRAINT ck_productos_precio CHECK (precio > 0),
  CONSTRAINT ck_productos_costo  CHECK (costo >= 0),
  CONSTRAINT ck_productos_activo CHECK (activo IN ('S', 'N')),
  CONSTRAINT ck_productos_calificacion CHECK (calificacion BETWEEN 0 AND 5),
  CONSTRAINT ck_productos_json CHECK (atributos IS JSON),
  CONSTRAINT fk_productos_categoria FOREIGN KEY (categoria_id)
    REFERENCES categorias (categoria_id)
);

-- ---------------------------------------------------------------------------
-- Empleados (jerarquía auto-referenciada)
-- ---------------------------------------------------------------------------
CREATE TABLE empleados (
  empleado_id   NUMBER(6)     CONSTRAINT pk_empleados PRIMARY KEY,
  nombre        VARCHAR2(100) NOT NULL,
  email         VARCHAR2(160) NOT NULL,
  manager_id    NUMBER(6),
  fecha_ingreso DATE          NOT NULL,
  salario       NUMBER(10,2)  NOT NULL,
  comision      NUMBER(5,2)   DEFAULT 0 NOT NULL,
  activo        CHAR(1)       DEFAULT 'S' NOT NULL,
  CONSTRAINT uq_empleados_email UNIQUE (email),
  CONSTRAINT ck_empleados_salario CHECK (salario > 0),
  CONSTRAINT ck_empleados_comision CHECK (comision BETWEEN 0 AND 100),
  CONSTRAINT ck_empleados_activo CHECK (activo IN ('S', 'N')),
  CONSTRAINT fk_empleados_manager FOREIGN KEY (manager_id)
    REFERENCES empleados (empleado_id)
);

-- ---------------------------------------------------------------------------
-- Pedidos y detalle
-- ---------------------------------------------------------------------------
CREATE TABLE pedidos (
  pedido_id              NUMBER(12)    CONSTRAINT pk_pedidos PRIMARY KEY,
  cliente_id             NUMBER(10)    NOT NULL,
  empleado_id            NUMBER(6),
  fecha_pedido           TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
  fecha_entrega_estimada DATE,
  fecha_entrega_real     TIMESTAMP(6) WITH TIME ZONE,
  estado                 VARCHAR2(20)  DEFAULT 'NUEVO' NOT NULL,
  moneda                 CHAR(3)       DEFAULT 'MXN' NOT NULL,
  subtotal               NUMBER(14,2)  DEFAULT 0 NOT NULL,
  impuesto               NUMBER(14,2)  DEFAULT 0 NOT NULL,
  descuento              NUMBER(14,2)  DEFAULT 0 NOT NULL,
  total                  NUMBER(14,2)  DEFAULT 0 NOT NULL,
  notas                  CLOB,
  creado_por             VARCHAR2(30)  DEFAULT USER NOT NULL,
  tiempo_entrega         INTERVAL DAY(3) TO SECOND(0),
  version                NUMBER(10)    DEFAULT 1 NOT NULL,
  CONSTRAINT ck_pedidos_estado CHECK (estado IN
    ('NUEVO', 'CONFIRMADO', 'ENVIADO', 'ENTREGADO', 'CANCELADO')),
  CONSTRAINT ck_pedidos_moneda CHECK (moneda IN ('MXN', 'USD', 'EUR')),
  CONSTRAINT ck_pedidos_totales CHECK
    (subtotal >= 0 AND impuesto >= 0 AND descuento >= 0 AND total >= 0),
  CONSTRAINT fk_pedidos_cliente FOREIGN KEY (cliente_id)
    REFERENCES clientes (cliente_id),
  CONSTRAINT fk_pedidos_empleado FOREIGN KEY (empleado_id)
    REFERENCES empleados (empleado_id) DEFERRABLE INITIALLY DEFERRED
);

CREATE TABLE pedido_detalle (
  detalle_id       NUMBER(12)   GENERATED BY DEFAULT AS IDENTITY
                                CONSTRAINT pk_pedido_detalle PRIMARY KEY,
  pedido_id        NUMBER(12)   NOT NULL,
  producto_id      NUMBER(10)   NOT NULL,
  cantidad         NUMBER(10,3) NOT NULL,
  precio_unitario  NUMBER(12,4) NOT NULL,
  descuento_pct    NUMBER(5,2)  DEFAULT 0 NOT NULL,
  total_linea      NUMBER(14,2) NOT NULL,
  CONSTRAINT uq_detalle_pedido_producto UNIQUE (pedido_id, producto_id),
  CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_detalle_descuento CHECK (descuento_pct BETWEEN 0 AND 100),
  CONSTRAINT fk_detalle_pedido FOREIGN KEY (pedido_id)
    REFERENCES pedidos (pedido_id) ON DELETE CASCADE,
  CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id)
    REFERENCES productos (producto_id)
);

CREATE TABLE pagos (
  pago_id          NUMBER(12)   CONSTRAINT pk_pagos PRIMARY KEY,
  pedido_id        NUMBER(12)   NOT NULL,
  fecha_pago       TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  metodo           VARCHAR2(20) NOT NULL,
  monto            NUMBER(14,2) NOT NULL,
  referencia       RAW(16),
  confirmado       CHAR(1)      DEFAULT 'N' NOT NULL,
  datos_respuesta  CLOB,
  CONSTRAINT ck_pagos_metodo CHECK
    (metodo IN ('TARJETA', 'TRANSFERENCIA', 'EFECTIVO', 'PAYPAL')),
  CONSTRAINT ck_pagos_confirmado CHECK (confirmado IN ('S', 'N')),
  CONSTRAINT ck_pagos_monto CHECK (monto > 0),
  CONSTRAINT ck_pagos_json CHECK (datos_respuesta IS JSON),
  CONSTRAINT fk_pagos_pedido FOREIGN KEY (pedido_id)
    REFERENCES pedidos (pedido_id)
);

-- ---------------------------------------------------------------------------
-- Auditoría e historial (CLOB + marcas de tiempo)
-- ---------------------------------------------------------------------------
CREATE TABLE auditoria_cambios (
  auditoria_id  NUMBER(18) GENERATED BY DEFAULT AS IDENTITY
                           CONSTRAINT pk_auditoria PRIMARY KEY,
  tabla         VARCHAR2(30) NOT NULL,
  operacion     CHAR(1)      NOT NULL,
  pk_valor      VARCHAR2(100),
  usuario       VARCHAR2(30) NOT NULL,
  fecha         TIMESTAMP(6) WITH LOCAL TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  datos_antes   CLOB,
  datos_despues CLOB,
  origen        VARCHAR2(20) DEFAULT 'TRIGGER' NOT NULL,
  CONSTRAINT ck_auditoria_operacion CHECK (operacion IN ('I', 'U', 'D'))
);

CREATE TABLE precios_historial (
  historial_id   NUMBER(18)   CONSTRAINT pk_precios_historial PRIMARY KEY,
  producto_id    NUMBER(10)   NOT NULL,
  precio_anterior NUMBER(12,2) NOT NULL,
  precio_nuevo   NUMBER(12,2) NOT NULL,
  fecha          TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  usuario        VARCHAR2(30) NOT NULL,
  CONSTRAINT fk_historial_producto FOREIGN KEY (producto_id)
    REFERENCES productos (producto_id)
);

-- ---------------------------------------------------------------------------
-- Comentarios de diccionario (se conservan en la migración)
-- ---------------------------------------------------------------------------
COMMENT ON TABLE clientes IS 'Clientes del canal comercial; incluye objeto y colección anidada';
COMMENT ON COLUMN clientes.datos_extra IS 'Atributos JSON almacenados como CLOB con CHECK IS JSON';
COMMENT ON TABLE pedidos IS 'Cabecera de pedidos; DATE/TIMESTAMP/INTERVAL y totales calculados';
COMMENT ON TABLE pedido_detalle IS 'Detalle de pedidos con identidad y total_linea por trigger';
COMMENT ON TABLE auditoria_cambios IS 'Bitácora de cambios escrita por paquetes y triggers';
COMMENT ON TABLE precios_historial IS 'Historial de cambios de precio de productos';

SHOW ERRORS
